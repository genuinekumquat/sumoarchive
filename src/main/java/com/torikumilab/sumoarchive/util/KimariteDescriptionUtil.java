	/**
	 * 한국어 설명 반환. 매핑되지 않은 경우 null.
	 */
	public static String getKr(String raw) {
		if (raw == null || raw.isBlank()) {
			return null;
		}
		String kr = KimariteDisplayUtil.toKr(raw);
		return KR_DESC.get(kr);
	}

